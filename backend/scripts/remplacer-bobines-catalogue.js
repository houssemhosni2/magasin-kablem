// Les deux premiers groupes ont une référence par ligne (elles contiennent des espaces) ; le dernier, plusieurs par ligne
const ARTICLES = GROUPES.flatMap(([, parPalette, texte]) =>
  (parPalette === 6 ? texte.split(/\s+/) : texte.split('\n'))
    .map(normaliserReference).filter(Boolean)
    .map((reference) => [reference, 'bobine', 'BOBINE', parPalette]));

(async () => {
  const doublons = ARTICLES.map((a) => a[0]).filter((r, i, t) => t.indexOf(r) !== i);
  if (doublons.length) throw new Error('Référence en double dans la liste : ' + doublons.join(', '));

  const c = await mysql.createConnection({
    host: process.env.DB_HOST, port: process.env.DB_PORT, user: process.env.DB_USER,
    password: process.env.DB_PASSWORD, database: process.env.DB_NAME,
  });
  try {
    const [anciennes] = await c.query("SELECT reference, famille, categorie FROM articles_mp WHERE famille = 'bobine' ORDER BY reference");
    const dossier = path.join(__dirname, 'sauvegardes');
    fs.mkdirSync(dossier, { recursive: true });
    const sauvegarde = path.join(dossier, `articles-bobines-avant-${new Date().toISOString().slice(0, 10)}.json`);
    fs.writeFileSync(sauvegarde, JSON.stringify(anciennes, null, 1));

    await c.beginTransaction();
    const [effacees] = await c.query("DELETE FROM articles_mp WHERE famille = 'bobine'");
    // une référence déjà connue comme cosse/connecteur devient bobine
    await c.query(
      `INSERT INTO articles_mp (reference, famille, categorie, bobines_par_palette) VALUES ?
       ON DUPLICATE KEY UPDATE famille = VALUES(famille), categorie = VALUES(categorie), bobines_par_palette = VALUES(bobines_par_palette)`,
      [ARTICLES]
    );
    await c.commit();

    const [parEmballage] = await c.query(
      "SELECT bobines_par_palette AS par_palette, COUNT(*) AS n FROM articles_mp WHERE famille = 'bobine' GROUP BY bobines_par_palette ORDER BY bobines_par_palette");
    console.log(`Sauvegarde des ${anciennes.length} anciennes bobines : ${sauvegarde}`);
    console.log(`${effacees.affectedRows} bobine(s) effacée(s), ${ARTICLES.length} entrée(s) :`);
    for (const e of parEmballage) console.log(`  ${e.par_palette} par palette : ${e.n}`);
  } catch (e) {
    await c.rollback().catch(() => {});
    console.error('Annulé, rien n\'a changé :', e.message);
    process.exitCode = 1;
  } finally {
    await c.end();
  }
})().catch((e) => {
  console.error(e.message);
  process.exitCode = 1;
});
